"""Build the website's photos from scripts/photos/photos.json.

For each photo: download the original once (cached in scripts/photos/.cache, gitignored),
crop it to its aspect ratio around a focus point, and save WebP files at each width into
site/img/<group>/<name>-<width>.webp. Also writes site/img/credits.json, which the About
page shows, so every photo is credited the way its licence asks.

All photos are free to use: Unsplash License, or Creative Commons / public domain from
Wikimedia Commons (credited, and marked "cropped and resized").

Usage: python scripts/photos/build_photos.py [--only name1,name2] [--quality 72]
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import urllib.error
import urllib.request
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = Path(__file__).with_name("photos.json")
CACHE = Path(__file__).with_name(".cache")
OUT = ROOT / "site" / "img"
UA = "CwtchAndCakePortfolio/1.0 (student portfolio project; photos are credited)"


def download(url: str, fallback: str | None) -> Image.Image:
    CACHE.mkdir(exist_ok=True)
    cached = CACHE / (hashlib.sha256(url.encode()).hexdigest()[:20] + ".img")
    if not cached.exists():
        data = None
        for candidate in [url] + ([fallback] if fallback else []):
            try:
                req = urllib.request.Request(candidate, headers={"User-Agent": UA})
                data = urllib.request.urlopen(req, timeout=90).read()
                break
            except urllib.error.HTTPError:
                continue  # e.g. the original is smaller than the requested thumbnail size
        if data is None:
            raise RuntimeError(f"could not download {url}")
        cached.write_bytes(data)
    return ImageOps.exif_transpose(Image.open(io.BytesIO(cached.read_bytes()))).convert("RGB")


def crop(im: Image.Image, aspect: str, fx: float, fy: float, zoom: float = 1.0) -> Image.Image:
    """The largest crop of this aspect ratio, divided by `zoom` (2 = half as wide), centred on the focus point."""
    aw, ah = (int(x) for x in aspect.split(":"))
    target = aw / ah
    w, h = im.size
    cw, ch = (round(h * target), h) if w / h > target else (w, round(w / target))
    cw, ch = round(cw / zoom), round(ch / zoom)
    left = min(max(round(fx * w - cw / 2), 0), w - cw)
    top = min(max(round(fy * h - ch / 2), 0), h - ch)
    return im.crop((left, top, left + cw, top + ch))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--quality", type=int, default=72)
    args = ap.parse_args()
    only = {n for n in args.only.split(",") if n}
    photos = json.loads(MANIFEST.read_text(encoding="utf-8"))

    credits = {}
    total = 0
    for p in photos:
        credits[p["name"]] = {"alt": p["alt"], **p["credit"]}
        if only and p["name"] not in only:
            continue
        im = crop(download(p["src"], p.get("fallback")), p["aspect"], *p["focus"], p.get("zoom", 1.0))
        folder = OUT / p["group"]
        folder.mkdir(parents=True, exist_ok=True)
        aw, ah = (int(x) for x in p["aspect"].split(":"))
        made = []
        for width in p["widths"]:
            width = min(width, im.width)  # never upscale
            resized = im.resize((width, round(width * ah / aw)), Image.LANCZOS)
            path = folder / f"{p['name']}-{width}.webp"
            resized.save(path, "WEBP", quality=args.quality, method=6)
            total += path.stat().st_size
            made.append(f"{width}w {path.stat().st_size // 1024}KB")
        print(f"{p['group']}/{p['name']}: {', '.join(made)}")

    (OUT / "credits.json").write_text(json.dumps(credits, indent=1, ensure_ascii=False), encoding="utf-8")

    # What the pages need to build responsive <img> tags: the widths that really exist on disk.
    data = {}
    for p in photos:
        widths = sorted(int(f.stem.rsplit("-", 1)[1]) for f in (OUT / p["group"]).glob(f"{p['name']}-*.webp")
                        if f.stem.rsplit("-", 1)[0] == p["name"])
        data[p["name"]] = {"group": p["group"], "aspect": p["aspect"], "widths": widths, "alt": p["alt"]}
    js = ("// Generated by scripts/photos/build_photos.py from scripts/photos/photos.json. Don't edit by hand.\n"
          f"export const PHOTOS = {json.dumps(data, indent=1, ensure_ascii=False)};\n")
    (ROOT / "site" / "js" / "photo-data.js").write_text(js, encoding="utf-8")
    print(f"{len(photos)} photos credited; {total // 1024} KB written; site/js/photo-data.js updated")


if __name__ == "__main__":
    main()
